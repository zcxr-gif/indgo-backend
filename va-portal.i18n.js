    var STORAGE_KEY = 'va_portal_lang';

    function pickInitialLang() {
        try {
            var saved = localStorage.getItem(STORAGE_KEY);
            if (saved && STRINGS[saved]) return saved;
        } catch (e) {}
        var nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
        var base = nav.split('-')[0];
        return STRINGS[base] ? base : 'en';
    }

    var current = pickInitialLang();

    // Translate a key for the active language, with {var} interpolation.
    // Falls back: current → English → the raw key, so text is never blank.
    function t(key, vars) {
        var table = STRINGS[current] || STRINGS.en;
        var s = table[key];
        if (s == null) s = STRINGS.en[key];
        if (s == null) return key;
        if (vars) {
            s = s.replace(/\{(\w+)\}/g, function (m, name) {
                return vars[name] != null ? vars[name] : m;
            });
        }
        return s;
    }

    // Walk the DOM and localise every tagged node. Idempotent — safe to re-run
    // after a language change or after new markup is injected.
    function applyI18n(root) {
        var scope = root || document;
        scope.querySelectorAll('[data-i18n]').forEach(function (el) {
            el.textContent = t(el.getAttribute('data-i18n'));
        });
        scope.querySelectorAll('[data-i18n-html]').forEach(function (el) {
            el.innerHTML = t(el.getAttribute('data-i18n-html'));
        });
        scope.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
            el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
        });
        scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
            var v = t(el.getAttribute('data-i18n-title'));
            el.setAttribute('title', v);
            if (!el.getAttribute('aria-label')) el.setAttribute('aria-label', v);
        });
        // Keep <html lang> and the document title honest for a11y / SEO.
        document.documentElement.setAttribute('lang', current);
        var titleEl = document.querySelector('title[data-i18n]');
        if (titleEl) document.title = t(titleEl.getAttribute('data-i18n'));
    }

    function setLang(code) {
        if (!STRINGS[code]) return;
        current = code;
        try { localStorage.setItem(STORAGE_KEY, code); } catch (e) {}
        applyI18n();
        // Let the page re-render any dynamic (JS-built) content in the new language.
        document.dispatchEvent(new CustomEvent('i18n:changed', { detail: { lang: code } }));
    }

    window.I18N = {
        t: t,
        apply: applyI18n,
        setLang: setLang,
        get lang() { return current; },
        langs: LANGS,
    };
    // Convenience global used throughout the page's inline script.
    window.t = t;
